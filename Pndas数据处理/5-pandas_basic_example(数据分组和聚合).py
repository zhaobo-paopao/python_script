# 数据分组与聚合可以对数据进行统计分析，如求和、求平均值、计数等。
import pandas as pd

data = {
   'city': ['北京','上海','广州','北京','上海'],
   'sales': [100,200,150,120,180]
   }
df = pd.DataFrame(data)
# print(df)

# 数据分组与聚合
grouped_df = df.groupby('city')['sales'].sum()
print(grouped_df)


'''
在 Python 中，%03d 是格式化字符串的一种写法（属于旧式字符串格式化，即 % 格式化)
，而 03d 核心是对整数进行格式化的指令，
常和字符串拼接 / 格式化结合使用。下面分核心用法、扩展场景、替代方案三部分详细说明;
'''
'''
一、%03d 的核心含义
拆解 %03d;
%;格式化占位符的起始标记;
0;填充字符（表示用 0 填充，而非默认的空格);
3;最小宽度（表示格式化后的字符串至少占 3 个字符位);
d;格式类型(表示接收整数(decimal)，若传入非整数会报错)。
作用;将整数格式化为固定 3 位的字符串，不足 3 位时左侧补 0,超过 3 位则按实际位数显示。
'''
# 1. 单个整数格式化
# 不足 3 位，左侧补 0
num1 = 5
res1 = "%03d" % num1
print(res1)  # 输出：005

# 刚好 3 位，原样显示
num2 = 123
res2 = "%03d" % num2
print(res2)  # 输出：123

# 超过 3 位，按实际位数显示
num3 = 4567
res3 = "%03d" % num3
print(res3)  # 输出：4567
# 2. 结合字符串拼接
# 场景：生成固定格式的编号（如订单号、序号）
order_id = 8
order_str = "订单编号：%03d" % order_id
print(order_str)  # 输出：订单编号：008

# 多个占位符（需用元组传参）
year, month, day = 2025, 1, 7
date_str = "日期：%04d-%02d-%02d" % (year, month, day)
print(date_str)  # 输出：日期：2025-01-07
# 三、扩展场景：其他格式化方式中的 03d
# 除了旧式 % 格式化，Python 还有两种主流格式化方式也支持 03d 规则：
num = 9
# 方式1：位置占位
res = "{:03d}".format(num)
print(res)  # 输出：009

# 方式2：嵌入字符串
name = "商品"
code = 12
msg = "{}-编号：{:03d}".format(name, code)
print(msg)  # 输出：商品-编号：012

# 2. f-string（Python 3.6+，推荐）
# 最简洁、高效的方式，直接在字符串中嵌入表达式：
num = 23
# 基础用法
res = f"{num:03d}"
print(res)  # 输出：023

# 结合复杂场景（如循环生成序号）
for i in range(5):
    print(f"第{i+1:03d}条数据")
# 输出：
# 第001条数据
# 第002条数据
# 第003条数据
# 第004条数据
# 第005条数据
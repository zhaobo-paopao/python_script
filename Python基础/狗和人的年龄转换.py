# 我家的狗5岁了，5岁的狗相当于多大年龄的人呢?
# 其实非常简单，狗的前两年每一年相当于人类的10.5岁,
# 然后每增加一年就增加四岁那么5岁的狗相等于人类的年龄就应该是10.5+10.5+4+4+4=33岁
# 编写一个程序，获取用户输入的狗的年龄，
# 然后通过程序显示其相当于人类的年龄。如果用户输入负数，请显示一个提示信息
dog_age=float(input('请输入狗的年龄:'))
person_age=0
if dog_age<0:
    print('狗的年龄输入错误,请重新输入')
elif dog_age<=2:
    person_age=10.5*dog_age
    print('狗的年龄是',dog_age,'岁','相当于人的',person_age,'岁')
else:
    person_age=10.5+10.5+(dog_age-2)*4
    print('狗的年龄是',dog_age,'岁','相当于人的',person_age,'岁')